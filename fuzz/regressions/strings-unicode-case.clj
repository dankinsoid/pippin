(require 'clojure.string)
(require 'clojure.set)

;; A case that prints megabytes drowns the divergence it was meant to show; the cut is the same on both sides.
(def fz-max-chars 20000)

(declare fz-norm)

(defn fz-pairs [m]
  (map (fn [e] [(fz-norm (key e)) (fz-norm (val e))]) (seq m)))

;; The comparison runs over this text, never over pr-str (docs/notes/fuzzing.md).
(defn fz-norm [x]
  (cond
    (map? x) (let [ps (fz-pairs x)
                   ps (if fz-sort-unordered (sort-by first ps) ps)]
               (str "{" (clojure.string/join ", " (map (fn [p] (str (first p) " " (second p))) ps)) "}"))
    (set? x) (let [es (map fz-norm x)
                   es (if fz-sort-unordered (sort es) es)]
               (str "#{" (clojure.string/join " " es) "}"))
    (and fz-bare-integers (integer? x)) (str x)
    (vector? x) (str "[" (clojure.string/join " " (map fz-norm x)) "]")
    (sequential? x) (str "(" (clojure.string/join " " (map fz-norm x)) ")")
    :else (pr-str x)))

(defn fz-emit [i s]
  (println (str i "\t" (if (> (count s) fz-max-chars) (str (subs s 0 fz-max-chars) " #fz/cut") s))))

;; Our jvm-hash against the oracle's own hash of the same value; the JVM's core has no jvm-hash to resolve.
(def fz-hash (if-let [v (resolve 'clojure.core/jvm-hash)] (deref v) hash))

(defn fz-out [x] (str (fz-norm x) " #fz/hash " (fz-hash x)))

;; What was thrown, raw: the JVM's class or our ex-type, and the message. The driver maps both to one error family
;; (fuzz/errors.edn); `type` is the class on the JVM, which has no ex-type to resolve.
(def fz-ex-type (when-let [v (resolve 'clojure.core/ex-type)] (deref v)))

(defn fz-throw [t]
  (str "#fz/throw " (if fz-ex-type (pr-str (fz-ex-type t)) (str (type t))) " " (pr-str (ex-message t))))

(defmacro fz [i expr]
  (list 'fz-emit i (list 'try (list 'fz-out expr) (list 'catch 'Throwable 'fz-t (list 'fz-throw 'fz-t)))))

;; Code point <-> string, which each side spells in its own way: a JVM char is a UTF-16 unit, ours a scalar.
(def uc-jvm? (nil? (resolve 'clojure.core/jvm-hash)))
(def uc-str (if uc-jvm? (eval (read-string "(fn [c] (String. (Character/toChars (int c))))")) (fn [c] (str (char c)))))
(def uc-cps (if uc-jvm? (eval (read-string "(fn [^String s] (vec (.toArray (.codePoints s))))")) (fn [s] (mapv int s))))

(defn uc-scalars [from to step] (remove #(<= 0xD800 % 0xDFFF) (range from to step)))

;; [cp upper lower] for the code points that case changes, each side 0 when it does not.
(defn uc-case [from to step]
  (vec (for [c (uc-scalars from to step)
             :let [s (uc-str c) u (clojure.string/upper-case s) l (clojure.string/lower-case s)]
             :when (or (not= u s) (not= l s))]
         [c (if (= u s) 0 (uc-cps u)) (if (= l s) 0 (uc-cps l))])))

(defn uc-text [cps] (apply str (map uc-str cps)))

;; Planes 0 and 1 whole, the CJK planes and the rest sampled.
(def uc-sample (uc-text (concat (uc-scalars 0 0x20000 1) (uc-scalars 0x20000 0x40000 7) (uc-scalars 0x40000 0xE0000 61)
                                (uc-scalars 0xE0000 0xE0200 1) (uc-scalars 0xE0200 0x110000 61))))
(def uc-sparse (uc-text (concat (uc-scalars 0 0x20000 5) (uc-scalars 0x20000 0x110000 37))))

;; What a pattern keeps of a text, one character at a time: how many, and the JVM's hash of them.
(defn uc-keep [text p]
  (let [kept (clojure.string/replace text (re-pattern (str "(?s)(?!" p ").")) "")]
    [(count (uc-cps kept)) (fz-hash kept)]))

(defn uc-matches? [p s] (try (boolean (re-matches (re-pattern p) s)) (catch Throwable _ :error)))
(defn uc-seq [p s] (mapv uc-cps (re-seq (re-pattern p) s)))

