;; the primitive entry (worker/wrapper): helpers whose every recorded caller passes int64 or double, called unboxed
;; from typed loops, boxed through the wrapper from the top level, with a wrong kind, throwing inside the worker
(defn sq [x] (* x x))
(defn half [x] (/ x 2.0))
(defn absd [x] (if (neg? x) (- 0 x) x))
(defn clampd [x] (let [y (* x 2)] (if (< y 10) y 10)))
(defn qr [a b] (+ (quot a b) (rem a b)))
(defn gcd [a b] (if (zero? b) a (recur b (rem a b))))
(defn hyp2 [a b] (+ (sq a) (sq b)))
(defn sum-sq [n] (loop [i 0 acc 0] (if (< i n) (recur (inc i) (+ acc (sq i))) acc)))
(defn sum-half [n] (loop [i 0 x 0.0 acc 0.0] (if (< i n) (recur (inc i) (+ x 1.0) (+ acc (half x))) acc)))
(defn sum-abs [n] (loop [i 0 acc 0] (if (< i n) (recur (inc i) (+ acc (absd (- 5 i)) (clampd i))) acc)))
(defn sum-qr [n] (loop [i 1 acc 0] (if (< i n) (recur (inc i) (+ acc (qr 100 i) (gcd 48 i) (hyp2 i 1))) acc)))
(defn qr-zero [] (qr 1 0))
(defn qr-min [] (qr -9223372036854775808 -1))
(defn sq-count [v] (sq (count v)))
