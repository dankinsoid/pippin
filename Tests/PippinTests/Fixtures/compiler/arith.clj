(defn dbl-mixed [i d] [(+ i d) (- d i) (* i d) (/ d i) (/ i d) (< i d) (>= d i) (= i d) (= d i)])
(defn dbl-lit [n] (loop [i 0 x 1.0 y -0.0] (if (< i n) (recur (inc i) (* x 2) (- y 0.25)) [x y (= x 8.0) (< y -0.5) (/ x 0.0) (- x ##Inf) (* y ##NaN)])))
